using System.Net.Http.Headers;
namespace ISTDocAi.Infrastructure.Services.DocAi.Analysis;

public sealed class BearerTokenHandler(BearerTokenCache cache) : DelegatingHandler
{
    protected override async Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken ct)
    {
        // Submit supplies the credential captured by its permit; never refresh it after Sending.
        if (request.Headers.Authorization is null)
            request.Headers.Authorization = new AuthenticationHeaderValue("Bearer", await cache.GetAsync(ct));
        return await base.SendAsync(request, ct);
    }
}
